num1 = int(input("Enter Value for num1 :"))
num2 = int(input("Enter Value for num2 : "))

#equality operator
result = num1 == num2
print(f"{result} = {num1} == {num2}")

#not equal operator
result = num1 != num2
print(f"{result} = {num1} != {num2}")

#less than operator
result = num1 < num2
print(f"{result} = {num1} < {num2}")

#greater than operator
result = num1 > num2
print(f"{result} = {num1} > {num2}")

#less than equal to operator
result = num1 <= num2
print(f"{result} = {num1} <= {num2}")

#greater than equal to operator
result = num1 >= num2
print(f"{result} = {num1} >= {num2}")