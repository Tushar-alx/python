#Example of Assignment Operator

a = 10
b = 5

# Arithmetic Operations with Assignment Operators
a += b  # Equivalent to a = a + b
print("Value of a after a += b:", a)

a -= b  # Equivalent to a = a - b
print("Value of a after a -= b:", a)

a *= b  # Equivalent to a = a * b
print("Value of a after a *= b:", a)

a /= b  # Equivalent to a = a / b
print("Value of a after a /= b:", a)

a %= b  # Equivalent to a = a % b
print("Value of a after a %= b:", a)

a //= b  # Equivalent to a = a // b
print("Value of a after a //= b:", a)

a **= b  # Equivalent to a = a ** b
print("Value of a after a **= b:", a)

